  function formatDuration(seconds) {
    const s = Math.floor(Number(seconds) || 0);
    if (s <= 0) return "";
    const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
    return h ? h + ":" + String(m).padStart(2, "0") + ":" + String(r).padStart(2, "0") : m + ":" + String(r).padStart(2, "0");
  }

  // NSFWDL refuses a file while this connection already reads its limit of
  // files at once (Free: 3). A slot frees only when one of them finishes,
  // which takes 5-15 minutes on a slow line, so a refused job waits that long
  // (15 s, then 30 s, then every minute) instead of failing. With 6 tries 15 s
  // apart, 12 of 20 refused xHamster/PornHub files never arrived (7 days to
  // 2026-10-12).
  const SLOT_WAIT_MS = 30 * 60 * 1000;

  function slotRetrySeconds(attempt, retryAfter) {
    return Math.max(Number(retryAfter) || 0, Math.min(60, 15 * 2 ** Math.max(0, attempt - 1)));
  }

  // What a job's row says, from the server's measured state only.
  function jobView(job) {
    switch (job.phase) {
      case "waiting":
        if (job.slotWaitSince) return {mode: "waiting", text: "Waiting for one of your downloads to finish…"};
        return {mode: "waiting", text: job.ahead > 0 ? "Waiting its turn · " + job.ahead + " ahead" : "Waiting its turn…"};
      case "starting": return {mode: "waiting", text: "Starting…"};
      case "queued": return {mode: "waiting", text: "Waiting for a free slot on NSFWDL…"};
      case "preparing": {
        const done = Number(job.bytesPrepared) || 0;
        if (done > 0 && job.sizeBytes && job.sizeBytes > done) {
          const fraction = Math.min(0.99, done / job.sizeBytes);
          return {mode: "measured", fraction, text: "Preparing " + Math.floor(fraction * 100) + "% · " + formatBytes(done) + " of ~" + formatBytes(job.sizeBytes)};
        }
        return {mode: "working", text: done > 0 ? "Preparing the file… " + formatBytes(done) : "Preparing the file…"};
      }
      case "saving": return {mode: "working", text: "Handing the file to your browser…"};
      case "receiving": return {mode: "working", text: "Your browser is downloading the file…"};
      case "stalled": return {mode: "stalled", text: "Your browser didn't start the download. Save it with the button below."};
      case "saved": return {mode: "done", text: "Saved to your downloads"};
      case "handed": return {mode: "done", text: "Handed to your browser. Check your downloads."};
      case "failed": return {mode: "error", text: job.error || "This download failed."};
      default: return {mode: "waiting", text: "…"};
    }
  }

