  // the chain.
  let syncTimer = 0;
  function scheduleSync() {
    clearTimeout(syncTimer);
    syncTimer = setTimeout(() => { try { sync(); } finally { scheduleSync(); } }, syncDelay());
  }
  scheduleSync();
  document.addEventListener("visibilitychange", () => { if (!document.hidden) { try { sync(); } finally { scheduleSync(); } } });
  scheduleMarks();
