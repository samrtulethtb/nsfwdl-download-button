  // After the hand-over the server reports whether the browser is reading
  // the file. If nothing arrives, offer a plain link: a fresh click on it
  // works where the automatic hand-over was blocked.
  async function followHandoff(job) {
    const startedAt = Date.now();
    while (Date.now() - startedAt < HANDOFF_DEADLINE_MS) {
      await sleep(POLL_MS);
      let status;
      try { status = await poll(job); } catch (_) { updateJob(job, {phase: "handed"}); return; }  // the one-time link expired
      if (status.handoff === "delivered") { updateJob(job, {phase: "saved"}); return; }
      if (status.handoff === "receiving") updateJob(job, {phase: "receiving"});
      else if (status.handoff === "stalled" || (status.handoff === "waiting" && Date.now() - startedAt > 10000)) {
        if (job.phase !== "stalled") updateJob(job, {phase: "stalled"});
      }
      if (status.state === "failed") {
        if (status.error_kind === "rate_limited_active_downloads" && requeue(job, 15)) return;
        updateJob(job, {phase: "failed", error: failureMessage(status.error_kind), retry: true});
        return;
      }
    }
    updateJob(job, {phase: "handed"});
  }

