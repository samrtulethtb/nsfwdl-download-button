  function normalizeFormats(data, supporterActive) {
    const formats = (data && Array.isArray(data.formats) ? data.formats : [])
      .filter((f) => f && typeof f.format_ref === "string" && f.format_ref && f.access !== "unsupported");
    const withVideo = formats.filter((f) => f.has_video !== false);
    const list = (withVideo.length ? withVideo : formats).map((f) => {
      const height = Number(f.height) || Number((String(f.quality_label || "").match(/(\d{3,4})p/) || [])[1]) || 0;
      const size = Number(f.estimated_size_bytes || f.filesize || f.filesize_approx) || 0;
      return {
        ref: f.format_ref,
        height,
        label: height ? height + "p" : String(f.quality_label || "Original").slice(0, 40),
        fps: Number(f.fps) > 30 ? Math.round(Number(f.fps)) : 0,
        sizeBytes: size > 0 ? size : null,
        sizeExact: f.size_kind === "exact",
        locked: f.access === "supporter" && !supporterActive,
        recommended: f.recommended === true,
        badge: qualityBadge(height),
      };
    });
    list.sort((a, b) => (b.height - a.height) || ((b.sizeBytes || 0) - (a.sizeBytes || 0)));
    const seen = new Set();
    return list.filter((c) => {
      const key = c.label + "|" + c.fps + "|" + c.locked;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
  }

