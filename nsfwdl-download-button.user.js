  // NSFWDL refused the file because this connection already reads 6: put
  // the job back in line and start it again a little later.
  function requeue(job, seconds) {
    if (job.attempts >= 6) return false;
    job.attempts += 1;
    updateJob(job, {phase: "waiting", notBefore: Date.now() + Math.max(5, seconds || 15) * 1000, id: null, fileUrl: null, bytesPrepared: 0});
    return true;
  }

  async function runJob(job) {
    job.phase = "starting";   // holds its slot from this moment
    job.notBefore = 0;
    render();
    try {
      const started = await api("POST", "/api/download", {format_ref: job.choice.ref, page_path: PAGE_PATH}, 30000);
      const fileUrl = safeDownloadUrl(started.download_url);
      const id = /^[A-Za-z0-9_-]{20,128}$/.test(String(started.download_id || "")) ? started.download_id : null;
      if (!fileUrl || !id) throw Object.assign(new Error("NSFWDL returned an unexpected answer. Try again."), {transient: true});
      if (state.jobs.some((other) => other !== job && other.id === id && activeJobs().includes(other))) {
        removeJob(job);   // the same download is already running (a repeated click)
        pump();
        render();
        return;
      }
      updateJob(job, {id, fileUrl, phase: started.state === "ready" ? "saving" : started.state === "queued" ? "queued" : "preparing"});
      if (started.state !== "ready") await waitUntilReady(job);
      updateJob(job, {phase: "saving"});
      saveFile(fileUrl);
      await followHandoff(job);
    } catch (error) {
      if (error && error.kind === "rate_limited_active_downloads" && requeue(job, error.retryAfter)) return;
      updateJob(job, {
        phase: "failed",
        error: (error && error.message) || "This download failed.",
        retry: Boolean(error && error.transient),
        supporter: Boolean(error && error.supporter),
      });
      if (!state.open) { state.open = true; renderDock(); render(); }
    }
  }

  async function poll(job) {
    let misses = 0;
    for (;;) {
      try {
        return await api("GET", "/api/download/" + encodeURIComponent(job.id) + "/status", null, 20000);
      } catch (error) {
        // A dropped poll is not a failed job; the server keeps working.
        if (!error.transient || ++misses >= 5) throw error;
        await sleep(1000 * misses);
      }
    }
  }

  async function waitUntilReady(job) {
    const deadline = Date.now() + PREPARE_DEADLINE_MS;
    while (Date.now() < deadline) {
      await sleep(POLL_MS);
      const status = await poll(job);
      if (status.state === "ready") return;
      if (status.state === "failed") {
        throw Object.assign(new Error(failureMessage(status.error_kind)), {transient: !["file_too_large_free", "file_exceeded_free_safety_ceiling", "geo_blocked", "media_unavailable", "paid_content"].includes(status.error_kind), supporter: /^file_(too_large|exceeded)_free/.test(String(status.error_kind || ""))});
      }
      updateJob(job, {phase: status.state === "queued" ? "queued" : "preparing", bytesPrepared: Number(status.bytes_prepared) || 0});
    }
    throw Object.assign(new Error("Preparing this file took too long. Try again or open it on NSFWDL."), {transient: true});
  }

